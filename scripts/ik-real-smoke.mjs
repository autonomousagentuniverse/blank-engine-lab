/** Real Three.js + Rapier IK integration smoke, no network/credentials at runtime. */
import assert from 'node:assert/strict';
import * as THREE from 'three';
import RAPIER from '@dimforge/rapier3d-compat';
import {createCharacterRig} from '../character/rig.mjs';
import {createPoseController,applyTwoBoneIK} from '../character/ik.mjs';
import {makePhysicsWorld} from '../physics/rapier.mjs';
import {playableLayout} from '../quest.mjs';
import {DEFAULT_SPEC} from '../core.mjs';
await RAPIER.init();
const layout=playableLayout({...DEFAULT_SPEC,buildings:6,robots:4});
const physics=makePhysicsWorld(RAPIER,layout);
const floor=physics.probeGround(layout.spawn.x,layout.spawn.z,1.2);
assert(floor&&Math.abs(floor.y)<.05, 'downward probe must see floor, not player capsule');
const ramp=physics.getTerrain()[0];
assert(ramp,'real calibration ramp is required');
const hit=physics.probeGround(ramp.position.x,ramp.position.z,2);
assert(hit?.y>.40,'ground ray should hit the raised ramp surface');
assert(hit.normal.y>.9&&Math.abs(hit.normal.z)>.05,'ray normal must reflect real surface slope');
assert(floor.normal.y>.95);
const rig=createCharacterRig(THREE,{makeMaterial:(color,other={})=>new THREE.MeshStandardMaterial({color,...other})});
const scene=new THREE.Scene();scene.add(rig.root);
const ik=createPoseController(THREE,rig);
assert.deepEqual(ik.chains.sort(),['leftArm','leftLeg','rightArm','rightLeg']);
const actor={grounded:true, y:0,vx:0,vz:0,motion:'idle'};
rig.update(actor,1/60);
rig.root.position.set(layout.spawn.x,0,layout.spawn.z);
rig.root.updateWorldMatrix(true,true);
const leg=rig.poseChains.leftLeg;
const before=leg.lower.localToWorld(new THREE.Vector3().copy(leg.endLocal));
ik.update({actor,dt:1/60,groundProbe:(x,z,y)=>physics.probeGround(x,z,y)});
const after=leg.lower.localToWorld(new THREE.Vector3().copy(leg.endLocal));
assert(Number.isFinite(after.y),'leg remains finite under real Three.js');
assert(Math.abs(after.y-.035)<=Math.abs(before.y-.035)+.08,'foot moves toward contact');
const shoulder=rig.poseChains.rightArm.upper.getWorldPosition(new THREE.Vector3());
const handTarget={x:shoulder.x+.3,y:shoulder.y-.55,z:shoulder.z-.2};
assert.equal(applyTwoBoneIK(THREE,rig.poseChains.rightArm,handTarget,{x:shoulder.x+.4,y:shoulder.y,z:shoulder.z-.5},.75),true);
ik.update({actor,dt:1/60,groundProbe:(x,z,y)=>physics.probeGround(x,z,y),handTarget,reach:1});
assert.equal(physics.position.y,0,'IK must not move physics body');
physics.dispose();
console.log('REAL IK SMOKE: PASS; 4 limb chains, Rapier downward probe, foot IK and hand reach');
