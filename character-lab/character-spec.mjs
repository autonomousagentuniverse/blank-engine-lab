export const MAX_CHARACTER_BYTES=32*1024*1024;
export function inspectLabGlb(arrayBuffer){
  if(!(arrayBuffer instanceof ArrayBuffer)||arrayBuffer.byteLength<20||arrayBuffer.byteLength>MAX_CHARACTER_BYTES)throw Error('A self-contained GLB between 20 bytes and 32 MiB is required');
  const view=new DataView(arrayBuffer);const size=arrayBuffer.byteLength;
  if(view.getUint32(0,true)!==0x46546c67||view.getUint32(4,true)!==2||view.getUint32(8,true)!==size)throw Error('Invalid glTF 2.0 binary header');
  const decode=new TextDecoder('utf-8',{fatal:true});let cursor=12,manifest=null;
  while(cursor<size){
    if(cursor+8>size)throw Error('Truncated GLB chunk header');
    const len=view.getUint32(cursor,true),type=view.getUint32(cursor+4,true);
    if(len%4||cursor+8+len>size)throw Error('Invalid GLB chunk bounds');
    if(type===0x4e4f534a){if(manifest)throw Error('Duplicate JSON chunk');
      manifest=JSON.parse(decode.decode(new Uint8Array(arrayBuffer,cursor+8,len)).trim());
    }
    cursor+=len+8;
  }
  if(cursor!==size||manifest?.asset?.version!=='2.0')throw Error('Not a valid glTF 2.0 GLB');
  if(!Array.isArray(manifest.skins)||!manifest.skins.length||manifest.skins.length>8)throw Error('Character requires a skinned rig');
  if(!Array.isArray(manifest.nodes)||manifest.nodes.length>1200||manifest.skins.some(s=>!Array.isArray(s.joints)||s.joints.length>256))throw Error('Skeleton budget exceeded');
  if((manifest.meshes?.length||0)>100||(manifest.animations?.length||0)>64)throw Error('Geometry or animation budget exceeded');
  if((manifest.extensionsRequired||[]).some(x=>!['KHR_materials_unlit'].includes(x)))throw Error('Unsupported mandatory glTF extensions');
  for(const resource of [...(manifest.images||[]),...(manifest.buffers||[])])if(typeof resource.uri==='string'&&!resource.uri.startsWith('data:'))throw Error('External sidecar resources are disallowed');
  return {manifest,bytes:size,skins:manifest.skins.length,bones:new Set(manifest.skins.flatMap(s=>s.joints)).size,meshes:(manifest.meshes||[]).length,materialSlots:(manifest.materials||[]).length,animationNames:(manifest.animations||[]).map((a,i)=>a.name||`Clip ${i+1}`)};
}
export function auditLoadedCharacter(root,clips=[],{THREE}={}){
 if(!root?.traverse||!Array.isArray(clips))throw Error('Character scene unavailable');
 let vertices=0,triangles=0,skinnedMeshes=0;const textures=new Set(),materials=new Set(),bones=new Set(),meshNames=[];
 root.traverse(o=>{
  if(o.isBone)bones.add(o.name);
  if(o.isMesh){
   meshNames.push(o.name||`Mesh ${meshNames.length+1}`);
   if(o.isSkinnedMesh)skinnedMeshes++;
   const geo=o.geometry,idx=geo?.index;vertices+=geo?.getAttribute('position')?.count||0;
   triangles+=Math.floor((idx?.count||geo?.getAttribute('position')?.count||0)/3);
   for(const m of (Array.isArray(o.material)?o.material:o.material?[o.material]:[])){
    materials.add(m);
    for(const v of Object.values(m))if(v?.isTexture)textures.add(v);
   }
  }
 });
 const warnings=[];
 if(skinnedMeshes===0)warnings.push('No skinned meshes found');
 if(textures.size===0)warnings.push('No image textures; material realism is limited');
 if(!clips.length)warnings.push('No authored animations; external motion required');
 if(vertices>180000)warnings.push('High geometry cost for mobile');
 const images=[...textures].map(t=>t.image??t.source?.data??{});
 const decodedTextureBytes=images.reduce((n,i)=>n+(Number(i.width)||0)*(Number(i.height)||0)*4,0);
 if(decodedTextureBytes>64*1024*1024)warnings.push('High decoded texture memory for mobile');
 return {vertices,triangles,skinnedMeshes,bones:bones.size,meshNames,materials:materials.size,textures:textures.size,decodedTextureBytes,clips:clips.map(x=>x.name),warnings};
}
